package cli

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"gopkg.in/yaml.v3"
)

const (
	configRelPath   = ".slopguard/config.yaml"
	baselineRelPath = ".slopguard/baseline.json"
)

// projectConfig is the minimal Phase 1 project configuration written by init.
// Unknown YAML keys are intentionally not modelled: init only proposes a
// canonical file and never silently rewrites an existing one.
type projectConfig struct {
	Version  int          `yaml:"version"`
	Adapters []string     `yaml:"adapters"`
	Verify   verifyConfig `yaml:"verify,omitempty"`
}

type verifyConfig struct {
	Jobs int `yaml:"jobs,omitempty"`
}

func configPath(root string) string { return filepath.Join(root, filepath.FromSlash(configRelPath)) }
func baselinePath(root string) string {
	return filepath.Join(root, filepath.FromSlash(baselineRelPath))
}

// renderConfig renders the canonical Phase 1 config file.
func renderConfig(adapterNames []string) ([]byte, error) {
	if adapterNames == nil {
		adapterNames = []string{}
	}
	cfg := projectConfig{
		Version:  1,
		Adapters: adapterNames,
		Verify:   verifyConfig{Jobs: 2},
	}

	var body bytes.Buffer
	enc := yaml.NewEncoder(&body)
	enc.SetIndent(2)
	if err := enc.Encode(&cfg); err != nil {
		return nil, fmt.Errorf("render config: %w", err)
	}
	if err := enc.Close(); err != nil {
		return nil, fmt.Errorf("render config: %w", err)
	}

	header := "# SlopGuard project configuration. Generated by slopguard init.\n" +
		"# Re-running init prints a diff and only applies it with --yes.\n"
	return append([]byte(header), body.Bytes()...), nil
}

// loadConfig reads an existing project config. A missing file is reported with
// os.ErrNotExist so callers can fall back to defaults.
func loadConfig(root string) (projectConfig, error) {
	data, err := os.ReadFile(configPath(root))
	if err != nil {
		return projectConfig{}, err
	}
	var cfg projectConfig
	if err := yaml.Unmarshal(data, &cfg); err != nil {
		return projectConfig{}, fmt.Errorf("parse %s: %w", configRelPath, err)
	}
	return cfg, nil
}

// normalizeText converts a config file to a comparison-friendly form: UTF-8
// BOM removed and CRLF line endings normalized to LF.
func normalizeText(data []byte) []byte {
	data = bytes.TrimPrefix(data, []byte{0xEF, 0xBB, 0xBF})
	return bytes.ReplaceAll(data, []byte("\r\n"), []byte("\n"))
}

// formatDiff renders a compact unified-style diff between two text files.
func formatDiff(path string, oldText, newText []byte) string {
	a := splitLines(string(normalizeText(oldText)))
	b := splitLines(string(normalizeText(newText)))

	var out strings.Builder
	fmt.Fprintf(&out, "--- a/%s\n+++ b/%s\n", path, path)
	for _, line := range diffLines(a, b) {
		out.WriteString(line)
		out.WriteByte('\n')
	}
	return out.String()
}

func splitLines(s string) []string {
	s = strings.TrimSuffix(s, "\n")
	if s == "" {
		return nil
	}
	return strings.Split(s, "\n")
}

// diffLines computes a longest-common-subsequence based line diff.
func diffLines(a, b []string) []string {
	n, m := len(a), len(b)
	dp := make([][]int, n+1)
	for i := range dp {
		dp[i] = make([]int, m+1)
	}
	for i := n - 1; i >= 0; i-- {
		for j := m - 1; j >= 0; j-- {
			if a[i] == b[j] {
				dp[i][j] = dp[i+1][j+1] + 1
			} else if dp[i+1][j] >= dp[i][j+1] {
				dp[i][j] = dp[i+1][j]
			} else {
				dp[i][j] = dp[i][j+1]
			}
		}
	}

	var out []string
	i, j := 0, 0
	for i < n && j < m {
		switch {
		case a[i] == b[j]:
			out = append(out, " "+a[i])
			i++
			j++
		case dp[i+1][j] >= dp[i][j+1]:
			out = append(out, "-"+a[i])
			i++
		default:
			out = append(out, "+"+b[j])
			j++
		}
	}
	for ; i < n; i++ {
		out = append(out, "-"+a[i])
	}
	for ; j < m; j++ {
		out = append(out, "+"+b[j])
	}
	return out
}

// writeFileAtomic writes a file via a temporary sibling and rename so a failed
// write cannot leave a half-written config behind.
func writeFileAtomic(path string, data []byte, mode os.FileMode) error {
	dir := filepath.Dir(path)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	tmp, err := os.CreateTemp(dir, ".slopguard-tmp-*")
	if err != nil {
		return err
	}
	tmpName := tmp.Name()
	defer func() {
		_ = os.Remove(tmpName)
	}()
	if _, err := tmp.Write(data); err != nil {
		_ = tmp.Close()
		return err
	}
	if err := tmp.Chmod(mode); err != nil {
		_ = tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	return os.Rename(tmpName, path)
}
